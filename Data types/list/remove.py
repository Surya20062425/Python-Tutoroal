# we can remove the elements present in a list 
# we have mutliple ways 

# remove()
name =list ("honey", "harsha ", "surya")
# if i want to remove a specific element 

# then i want to know its index

name.remove(3)

# by the above  command i have removed surya from the above list


# pop()

# it actually removes the last element 
num= list(1,2,3,5,6,7,8)
num.pop() 
# we have removed 8 from list 

# because it is the last element

# del 

num = [14,3,4,5,6]

# it is used to delete a specific element from the list 

del num[2]
# we have deleted the element 4

# because we are deleting the elements based on the index



